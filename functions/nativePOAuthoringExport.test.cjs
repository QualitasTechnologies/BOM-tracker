const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
test('native PO authoring callable binds native auth and exact default-off gates',()=>{
  const source=fs.readFileSync(require.resolve('./index.js'),'utf8'),start=source.indexOf('// Native PO authoring'); assert.ok(start>=0);
  const {authoringEnabled}=require('./nativePOAuthoringOperations.cjs');
  const flags=['BOM_MATERIAL_MUTATIONS_ENABLED','BOM_NATIVE_MATERIAL_MUTATIONS_ENABLED','BOM_NATIVE_PO_AUTHORING_ENABLED'];
  for(let mask=0;mask<8;mask++) {
    const env=Object.fromEntries(flags.filter((_key,bit)=>mask&(1<<bit)).map(key=>[key,'true']));let dependencies,config;
    const context={exports:{},process:{env},admin:{auth:()=> 'auth',firestore:Object.assign(()=> 'db',{FieldValue:{serverTimestamp:()=> 'time'}})},
      require:name=>{assert.equal(name,'./nativePOAuthoringOperations.cjs');return{authoringEnabled,createNativePOAuthoringOperations:options=>{dependencies=options;return'handler';}};},
      onCall:(options,handler)=>{assert.equal(handler,'handler');config=options;return'callable';}};
    vm.runInNewContext(source.slice(start),context);assert.equal(context.exports.nativePOAuthoringOperations,'callable');
    assert.equal(dependencies.enabled(),mask===7);assert.equal(dependencies.auth,'auth');assert.equal(dependencies.db,'db');assert.equal(dependencies.getServerTimestamp(),'time');
    assert.equal(config.region,'us-central1');assert.equal(config.secrets,undefined);
  }
});
test('deployed domain artifact is generated from the original calculation source without manual drift',async()=>{
  const {transformWithEsbuild}=await import('vite'),{createHash}=require('node:crypto');
  const source=fs.readFileSync(require('node:path').join(__dirname,'../src/types/purchaseOrder.ts'),'utf8').replace(/\r\n/g,'\n');
  const {code}=await transformWithEsbuild(source,'purchaseOrder.ts',{format:'cjs',target:'node22'});
  const expected=`// Generated by scripts/build-po-domain.mjs from src/types/purchaseOrder.ts; SHA256 ${createHash('sha256').update(source).digest('hex')}\n${code}`;
  assert.equal(fs.readFileSync(require.resolve('./poDomain.generated.cjs'),'utf8').replace(/\r\n/g,'\n'),expected);
});
