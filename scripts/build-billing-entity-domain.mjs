import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import ts from 'typescript';
import { transformWithEsbuild } from 'vite';

const option = key => process.argv.find(value => value.startsWith(`--${key}=`))?.slice(key.length + 3);
const root = path.resolve(option('source-root') || '.');
const output = path.resolve(option('output') || 'functions/billingEntityDomain.generated.cjs');
const settingsText = (await readFile(path.join(root, 'src/utils/settingsFirestore.ts'), 'utf8')).replace(/\r\n/g, '\n');
const formText = (await readFile(path.join(root, 'src/components/settings/BillingEntitiesTab.tsx'), 'utf8')).replace(/\r\n/g, '\n');
const settings = ts.createSourceFile('settingsFirestore.ts', settingsText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const form = ts.createSourceFile('BillingEntitiesTab.tsx', formText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const variable = (source, name) => {
  const matches = source.statements.filter(ts.isVariableStatement).flatMap(node => [...node.declarationList.declarations]).filter(node => node.name.getText(source) === name);
  if (matches.length !== 1 || !matches[0].initializer) throw Error(`Expected one source definition: ${name}`);
  return matches[0].initializer;
};
const descendants = (node, predicate) => {
  const found = [];
  const visit = current => { if (predicate(current)) found.push(current); ts.forEachChild(current, visit); };
  visit(node); return found;
};
const defaults = descendants(variable(settings, 'getCompanySettings'), node => ts.isReturnStatement(node) && node.expression && ts.isObjectLiteralExpression(node.expression)
  && node.expression.properties.some(property => property.name?.getText(settings) === 'companyName'));
if (defaults.length !== 1) throw Error('Expected the original missing-company defaults');
const companyUpdates = descendants(variable(settings, 'updateBillingEntity'), node => ts.isCallExpression(node) && ts.isIdentifier(node.expression)
  && node.expression.text === 'updateCompanySettings' && node.arguments.length === 1 && ts.isObjectLiteralExpression(node.arguments[0]));
if (companyUpdates.length !== 1) throw Error('Expected the original primary alias mapping');
const names = ['companyAsBillingEntity', 'entityMatchesDatasensor', 'getDefaultBillingEntity', 'sortBillingEntities', 'billingEntityToCompanySettings'];
const pieces = names.map(name => `export const ${name} = ${variable(settings, name).getText(settings)};`);
pieces.push(`export const defaultCompanySettings = () => (${defaults[0].expression.getText(settings)});`);
pieces.push(`export const billingEntityPatchToCompanySettings = (updates: any) => (${companyUpdates[0].arguments[0].getText(settings)});`);
pieces.push(`export const emptyBillingEntity = ${variable(form, 'emptyEntity').getText(form)};`);
const source = pieces.join('\n\n');
const hash = createHash('sha256').update(source).digest('hex');
const { code } = await transformWithEsbuild(source, 'billingEntityDomain.ts', { format: 'cjs', target: 'node22' });
const generated = `// Generated by scripts/build-billing-entity-domain.mjs from the original Settings helpers/form; SHA256 ${hash}\n${code}`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replace(/\r\n/g, '\n') !== generated) throw Error('Billing entity domain is stale; regenerate from the original Settings source');
} else {
  await writeFile(output, generated);
}
