import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { transformWithEsbuild } from 'vite';
const source = (await readFile(new URL('../src/types/purchaseOrder.ts', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const hash = createHash('sha256').update(source).digest('hex');
const { code } = await transformWithEsbuild(source, 'purchaseOrder.ts', { format: 'cjs', target: 'node22' });
await writeFile(new URL('../functions/poDomain.generated.cjs', import.meta.url), `// Generated by scripts/build-po-domain.mjs from src/types/purchaseOrder.ts; SHA256 ${hash}\n${code}`);
